def ra_login(user, password):
    url = "https://retroachievements.org/dorequest.php?" + urllib.parse.urlencode(
        {"r": "login", "u": user, "p": password})
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "ThorSettings/1.0"}),
                                    timeout=20) as r:
            data = json.load(r)
    except Exception as e:  # network/HTTP/JSON: report, never crash the menu
        return None, str(e)
    return (data.get("Token"), "") if data.get("Success") else (None, data.get("Error", "Login failed"))


def page_cheevos(ui):
    p = "global.retroachievements"
    sel = 0
    while True:
        user = conf.get(f"{p}.username")
        items = [("RetroAchievements", "On" if conf.get(p) == "1" else "Off"),
                 ("Account", (user + (" (signed in)" if conf.get(f"{p}.token") else "")) if user else "Not signed in"),
                 ("Sign in…", "")]
        items += [(label, "On" if conf.get(f"{p}.{k}") == "1" else "Off") for label, k in CHEEVO_OPTS]
        sel = ui.menu("RetroAchievements", items, sel, lr=True)
        if sel is None:
            return
        if sel == 0:
            conf.set(p, "0" if conf.get(p) == "1" else "1")
        elif sel in (1, 2) and ui.last_action == "a":
            u = ui.keyboard("RetroAchievements username", user)
            if u is None:
                continue
            pw = ui.keyboard("RetroAchievements password", "", secret=True)
            if pw is None:
                continue
            ui.busy("RetroAchievements", "Signing in…")
            token, err = ra_login(u, pw)
            if token:
                conf.set(f"{p}.username", u)
                conf.set(f"{p}.password", pw)
                conf.set(f"{p}.token", token)
                conf.set(p, "1")
                ui.message("RetroAchievements", [f"Signed in as {u}."])
            else:
                ui.message("RetroAchievements", ["Sign-in failed:", err[:120]])
        elif sel >= 3:
            k = f"{p}.{CHEEVO_OPTS[sel - 3][1]}"
            conf.set(k, "0" if conf.get(k) == "1" else "1")


def os_release():
    d = {}
    try:
        for line in open("/etc/os-release"):
            k, _, v = line.strip().partition("=")
            d[k] = v.strip('"')
    except OSError:
        pass
    return d


