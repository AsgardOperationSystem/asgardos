# --- system.cfg ---------------------------------------------------------------
class Conf:
    """key=value file. Writes are atomic (temp file + rename) so a crash can't truncate it."""

    def __init__(self, path=CFG):
        self.path = path

    def _lines(self):
        with open(self.path, encoding="utf-8", errors="replace") as f:
            return f.read().splitlines()

    def get(self, key, default=""):
        for line in self._lines():
            k, sep, v = line.partition("=")
            if sep and k == key:
                return v
        return default

    def set(self, key, value):
        """value None removes the key (= back to default)."""
        lines, done = [], False
        for line in self._lines():
            if line.partition("=")[0] == key:
                if value is not None and not done:
                    lines.append(f"{key}={value}")
                done = True
            else:
                lines.append(line)
        if value is not None and not done:
            lines.append(f"{key}={value}")
        tmp = self.path + ".thor-tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, os.stat(self.path).st_mode & 0o777)
        os.replace(tmp, self.path)


conf = Conf()


# --- ROCKNIX data ---------------------------------------------------------------
def _feats(node):
    if node is None:
        return []
    return [(f.get("name"), [(c.get("name"), c.get("value", c.get("name"))) for c in f.findall("choice")])
            for f in node.findall("feature")]


