def _standard(attr):
    out = []
    for f in (x.strip() for x in (attr or "").split(",")):
        if f in STANDARD:
            key, choices = STANDARD[f]
            if choices is None:
                choices = shader_choices()
            out.append((key, choices))
    return out


def load_features():
    """(emulator, core) -> [(feature key, [(label, value)])]; core-level features extend the emulator's."""
    out = {}
    drivers = gpu_driver_choices()
    for emu in ET.parse(FEATURES).getroot().findall("emulator"):
        base = _standard(emu.get("features")) + _feats(emu.find("features"))
        if drivers:   # every emulator: only Vulkan ones load it, the rest ignore VK_DRIVER_FILES
            base = [("gpu driver", drivers)] + base
        base = PERF_FEATURES + base
        out[(emu.get("name"), None)] = base
        for core in emu.findall("cores/core"):
            extra = _standard(core.get("features")) + _feats(core.find("features"))
            out[(emu.get("name"), core.get("name"))] = base + [f for f in extra if f[0] not in {b[0] for b in base}]
    return out


def load_systems():
    """name -> dict(fullname, path, exts, emulator, core) using ROCKNIX's default emulator/core."""
    out = {}
    for s in ET.parse(SYSTEMS).getroot().findall("system"):
        emu = core = None
        for e in s.findall("emulators/emulator"):
            for c in e.findall("cores/core"):
                if c.get("default") == "true" or emu is None:
                    emu, core = e.get("name"), (c.text or "").strip()
        out[s.findtext("name")] = {"fullname": s.findtext("fullname"), "path": s.findtext("path"),
                                   "exts": tuple(x.lower() for x in s.findtext("extension", "").split()),
                                   "emulator": emu, "core": core}
    return out


def has_games(sysinfo):
    try:
        return any(e.is_file() and e.name.lower().endswith(sysinfo["exts"])
                   for e in os.scandir(sysinfo["path"]))
    except OSError:
        return False


